def main():
    covered = {}
    out = []
    ok = True
    for n, ep in enumerate(EPISODES, 1):
        words = sum(s["words"] for s in ep["scenes"])
        gaps = (len(ep["scenes"]) - 1) * GAP
        dur = words / WPS + gaps
        scenes = []
        for s in ep["scenes"]:
            for q in s["covers"]:
                if q in covered:
                    print(f"ERROR {q} covered twice (ep {covered[q]} and {n})"); ok = False
                covered[q] = n
            scenes.append({**s, "estimatedSeconds": round(s["words"] / WPS, 1)})
        questions = [q for s in ep["scenes"] for q in s["covers"]]
        within = abs(dur - TARGET) <= TOL
        ok &= within
        out.append({"episode": n, "title": ep["title"], "exercises": ep["exercises"], "questions": questions,
                    "scenes": scenes, "totalWords": words, "sceneCount": len(scenes),
                    "estimatedSeconds": round(dur, 1)})
        print(f"{'OK ' if within else 'BAD'} ep{n:02d}  {len(scenes):2d} scenes  {words:5d} words  {dur:6.1f} s   {ep['title']}")
    missing = [q for q in ALL_QUESTIONS if q not in covered]
    extra = [q for q in covered if q not in ALL_QUESTIONS]
    if missing or extra:
        print("missing:", missing, "unknown:", extra); ok = False
    plan = {"rules": {"wordsPerSecond": WPS, "gapBetweenScenesSeconds": GAP, "targetSeconds": TARGET, "toleranceSeconds": TOL},
            "episodes": out}
    pathlib.Path("plan/episodes.json").write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    total = sum(e["estimatedSeconds"] for e in out)
    print(f"total {total/60:.1f} min;", "ALL CHECKS PASSED" if ok else "CHECKS FAILED")
    raise SystemExit(0 if ok else 1)

if __name__ == "__main__":
    main()
