// يحوّل كل عنصر يحمل data-icon إلى أيقونة SVG
window.renderIcons = function (root) {
  (root || document).querySelectorAll('[data-icon]').forEach(el => {
    const name = el.getAttribute('data-icon');
    if (!ICONS[name] || el.querySelector(':scope > svg.ic')) return;
    el.insertAdjacentHTML('afterbegin', icon(name));
  });
};
window.icon = function (name, cls) {
  const fillIcons = ['play'];
  const fill = fillIcons.includes(name) ? 'currentColor' : 'none';
  return `<svg class="ic ${cls || ''}" viewBox="0 0 24 24" fill="${fill}" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><defs><linearGradient id="lg" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#155dfc"/><stop offset="1" stop-color="#00a6f4"/></linearGradient></defs>${ICONS[name] || ''}</svg>`;
};
